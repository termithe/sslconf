export type Locale = "en" | "es";

export const localeCookieName = "sslconf_locale";

export function isLocale(value: string | undefined): value is Locale {
  return value === "en" || value === "es";
}

export function isSpanishPath(pathname: string) {
  return pathname === "/es" || pathname.startsWith("/es/");
}

export function localizedPath(pathname: string, locale: Locale) {
  const withoutSpanishPrefix = pathname === "/es" ? "/" : pathname.replace(/^\/es(?=\/)/, "");
  if (locale === "en") return withoutSpanishPrefix;
  if (withoutSpanishPrefix === "/") return "/es";
  return `/es${withoutSpanishPrefix}`;
}

export function localeFromAcceptLanguage(header: string | null) {
  return header
    ?.split(",")
    .map((part) => part.trim().toLowerCase())
    .some((part) => part === "es" || part.startsWith("es-"))
    ? "es"
    : "en";
}

